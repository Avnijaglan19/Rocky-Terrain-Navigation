import pytest #testing framework
from src.mock_data import make_mock_grid #mock grid generator from mock data module
from src.search.dijkstra import dijkstra_search #Dijkstra search function
from src.search.astar import astar_search #A* search function
from src.grid_types import CellType #CellType enum for validation

def test_dijkstra_finds_path(): #test that Dijkstra finds a valid path on the mock terrain
    grid = make_mock_grid() #geneate the baseline mock grid
    path, metrics = dijkstra_search(grid) #execute Dijkstra search
    assert len(path) > 0 #assert that a path was returned
    assert path[0] == (0, 0) #assert that the path originates at the start coordinate (0,0)
    assert path[-1] == (5, 7) #assert that the path terminates at the city coordinate (5,7)
    assert metrics["algorithm"] == "dijkstra" #assert that the algorithm tag is correct
    assert metrics["health"] > 0 #assert that the robot finishes with positive health

def test_astar_finds_path(): #test that A* finds a valid path on the mock terrain
    grid = make_mock_grid() #generate the baseline mock grid
    path, metrics = astar_search(grid) #execute A* search
    assert len(path) > 0 #assert that a path was returned
    assert path[0] == (0, 0) #assert that the path originates at the start coordinate (0,0)
    assert path[-1] == (5, 7) #assert that the path terminates at the city coordinate (5,7)
    assert metrics["algorithm"] == "astar" #assert that the algorithm tag is correct
    assert metrics["health"] > 0 #assert that the robot finishes with positive health

def test_astar_exploes_fewer_or_equal_nodes(): #test that A* explores fewer or equal nodes compared to Dijkstra
    grid = make_mock_grid() #generate the baseline mock grid
    _, d_metrics = dijkstra_search(grid) #run Dijkstra and capture metrics
    _, a_metrics = astar_search(grid) #run A* and capture metrics
    assert a_metrics["nodes_explored"] <= d_metrics["nodes_explored"] #assert A* heuristic guidance expands fewer or equal nodes than uniform search

def test_no_cliff_traversal(): #test that paths generated by search never step on cliff cells
    grid = make_mock_grid() #generate the baseline mock grid
    path, _ = astar_search(grid) #run A* search
    for r, c in path: #iterate through every set of coordinates in the computed path
        assert grid[r, c] != CellType.CLIFF #assert the coordinate is never an impassable cliff